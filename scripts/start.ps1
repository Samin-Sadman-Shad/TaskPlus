#Requires -Version 5.1
<#
.SYNOPSIS
    Starts the whole Smart Task system (SQL Server, API, web client) with Docker, with no manual setup.

.DESCRIPTION
    First run on a fresh clone:
      1. creates .env with strong random secrets and a generated admin password (only if .env is missing;
         an existing .env is never changed),
      2. creates the SQL Server data folders,
      3. creates the HTTPS certificate the API container needs (if missing),
      4. runs "docker compose up -d --build" and waits until the API and the web app answer.
    Later runs skip what already exists, so it is safe to run every time.

.PARAMETER NoBuild
    Start without rebuilding the images ("docker compose up -d").

.EXAMPLE
    ./scripts/start.ps1
#>
param([switch]$NoBuild)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

function Write-Step([string]$Text) { Write-Host "==> $Text" -ForegroundColor Cyan }

# Random string from an unambiguous alphabet, using a cryptographic RNG with rejection sampling (no bias).
function New-Secret([int]$Length) {
    $alphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789'
    $limit = 256 - (256 % $alphabet.Length)
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $buffer = New-Object byte[] 1
    $chars = New-Object System.Text.StringBuilder
    try {
        while ($chars.Length -lt $Length) {
            $rng.GetBytes($buffer)
            if ($buffer[0] -lt $limit) { [void]$chars.Append($alphabet[$buffer[0] % $alphabet.Length]) }
        }
    }
    finally { $rng.Dispose() }
    $chars.ToString()
}

# Meets SQL Server's and the app's password policy (upper, lower, digit, symbol). Only letters, digits
# and '-' are used, which are safe in .env, docker compose and the sqlcmd init script.
function New-Password { "$(New-Secret 24)-Aa9" }

function Read-DotEnv([string]$Path) {
    $values = @{}
    foreach ($line in Get-Content $Path) {
        if ($line -match '^\s*#' -or $line -notmatch '=') { continue }
        $key, $value = $line -split '=', 2
        $values[$key.Trim()] = $value.Trim()
    }
    $values
}

# ---- 1. Docker ---------------------------------------------------------------------------------
Write-Step 'Checking Docker'
docker info *> $null
if ($LASTEXITCODE -ne 0) { throw 'Docker is not running. Start Docker Desktop, then run this script again.' }

# ---- 2. .env -----------------------------------------------------------------------------------
$envPath = Join-Path $root '.env'
$createdEnv = $false
$adminPassword = $null
if (Test-Path $envPath) {
    Write-Step '.env exists - using it as is'
}
else {
    Write-Step 'Creating .env with generated secrets'
    $userHome = [Environment]::GetFolderPath('UserProfile') -replace '\\', '/'
    $adminPassword = New-Password
    $content = @"
# Generated by scripts/start.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm'). Local development only.
# Contains secrets: never commit this file (it is git-ignored).
COMPOSE_PROJECT_NAME=smarttask

API_HTTP_PORT=5180
API_HTTPS_PORT=7180
WEB_PORT=4200
SQL_PORT=1433

SQLSERVER_DATA_DIR=$userHome/.smarttask/sqlserver-data

MSSQL_SA_PASSWORD=$(New-Password)
APP_DB_NAME=SmartTaskDb
APP_DB_USER=smarttask_app
APP_DB_PASSWORD=$(New-Password)

JWT_SIGNING_KEY=$(New-Secret 64)

CERT_PASSWORD=$(New-Secret 32)
CERT_DIR=$userHome/.aspnet/https

# Optional: GitHub Models key; empty = the built-in fake AI provider
AI_API_KEY=

# First admin, created on the first start (only when no admin exists yet)
BOOTSTRAP_ADMIN_FIRST_NAME=System
BOOTSTRAP_ADMIN_LAST_NAME=Admin
BOOTSTRAP_ADMIN_EMAIL=admin@smarttask.local
BOOTSTRAP_ADMIN_PASSWORD=$adminPassword
"@
    # UTF-8 without BOM: docker compose reads a BOM as part of the first key.
    [System.IO.File]::WriteAllText($envPath, $content, (New-Object System.Text.UTF8Encoding($false)))
    $createdEnv = $true
}

$cfg = Read-DotEnv $envPath
$required = 'SQLSERVER_DATA_DIR', 'MSSQL_SA_PASSWORD', 'APP_DB_USER', 'APP_DB_PASSWORD', 'JWT_SIGNING_KEY', 'CERT_PASSWORD', 'CERT_DIR'
$missing = $required | Where-Object { -not $cfg[$_] -or $cfg[$_].StartsWith('<') }
if ($missing) { throw ".env is missing values for: $($missing -join ', '). Fill them in, or delete .env to have one generated." }

# ---- 3. Data folders ---------------------------------------------------------------------------
Write-Step "SQL Server data folders in $($cfg['SQLSERVER_DATA_DIR'])"
foreach ($sub in 'data', 'log') {
    New-Item -ItemType Directory -Force -Path (Join-Path $cfg['SQLSERVER_DATA_DIR'] $sub) | Out-Null
}

# ---- 4. HTTPS certificate for the API container -------------------------------------------------
$pfx = Join-Path $cfg['CERT_DIR'] 'smarttask-api.pfx'
if (Test-Path $pfx) {
    Write-Step 'HTTPS certificate exists'
}
else {
    Write-Step "Creating HTTPS certificate $pfx"
    New-Item -ItemType Directory -Force -Path $cfg['CERT_DIR'] | Out-Null
    if (Get-Command dotnet -ErrorAction SilentlyContinue) {
        dotnet dev-certs https -ep $pfx -p $cfg['CERT_PASSWORD'] | Out-Null
        if ($LASTEXITCODE -ne 0) { throw 'dotnet dev-certs could not export the certificate.' }
    }
    else {
        # No .NET SDK: make a self-signed localhost certificate with OpenSSL in a throwaway container.
        $mount = (Resolve-Path $cfg['CERT_DIR']).Path
        docker run --rm -e "PFX_PASSWORD=$($cfg['CERT_PASSWORD'])" -v "${mount}:/out" alpine:3.22 sh -c `
            'apk add --no-cache openssl >/dev/null && openssl req -x509 -newkey rsa:2048 -nodes -days 365 -subj "/CN=localhost" -addext "subjectAltName=DNS:localhost" -keyout /tmp/k.pem -out /tmp/c.pem 2>/dev/null && openssl pkcs12 -export -out /out/smarttask-api.pfx -inkey /tmp/k.pem -in /tmp/c.pem -passout env:PFX_PASSWORD'
        if ($LASTEXITCODE -ne 0) { throw 'Could not create the certificate with OpenSSL.' }
    }
}

# ---- 5. Start ----------------------------------------------------------------------------------
Write-Step 'Starting containers (first build takes a few minutes)'
if ($NoBuild) { docker compose up -d } else { docker compose up -d --build }
if ($LASTEXITCODE -ne 0) {
    throw "docker compose failed. If a port is in use, change WEB_PORT / API_HTTPS_PORT / SQL_PORT in .env and run again."
}

# ---- 6. Wait until it answers ------------------------------------------------------------------
$webPort = if ($cfg['WEB_PORT']) { $cfg['WEB_PORT'] } else { '4200' }
$apiPort = if ($cfg['API_HTTPS_PORT']) { $cfg['API_HTTPS_PORT'] } else { '7180' }
Write-Step 'Waiting for the API and the web app'
$ready = $false
for ($i = 0; $i -lt 60 -and -not $ready; $i++) {
    Start-Sleep -Seconds 3
    $api = & curl.exe -sk -o NUL -w '%{http_code}' "https://localhost:$apiPort/health/ready" 2>$null
    $web = & curl.exe -s -o NUL -w '%{http_code}' "http://localhost:$webPort/healthz" 2>$null
    $ready = ($api -eq '200' -and $web -eq '200')
}
if (-not $ready) {
    Write-Warning 'Not ready after 3 minutes. Check: docker compose ps   and   docker compose logs api'
    exit 1
}

# ---- 7. Summary --------------------------------------------------------------------------------
Write-Host ''
Write-Host 'Smart Task is running' -ForegroundColor Green
Write-Host "  Web app : http://localhost:$webPort"
Write-Host "  Swagger : https://localhost:$apiPort/swagger"
Write-Host "  Admin   : $($cfg['BOOTSTRAP_ADMIN_EMAIL'])"
if ($createdEnv) {
    Write-Host "  Password: $adminPassword" -ForegroundColor Yellow
    Write-Host '            (generated now; it is also in .env as BOOTSTRAP_ADMIN_PASSWORD)'
}
else {
    Write-Host '  Password: BOOTSTRAP_ADMIN_PASSWORD in .env (if this admin was created from .env)'
}
Write-Host '  Stop    : docker compose stop'
