#!/usr/bin/env bash
# Starts the whole Smart Task system (SQL Server, API, web client) with Docker, with no manual setup.
#
# First run on a fresh clone:
#   1. creates .env with strong random secrets and a generated admin password (only if .env is missing;
#      an existing .env is never changed),
#   2. creates the SQL Server data folders,
#   3. creates the HTTPS certificate the API container needs (if missing),
#   4. runs "docker compose up -d --build" and waits until the API and the web app answer.
# Later runs skip what already exists, so it is safe to run every time.
#
# Usage: ./scripts/start.sh [--no-build]
set -euo pipefail

cd "$(dirname "$0")/.."
step() { printf '\033[36m==> %s\033[0m\n' "$1"; }
fail() { printf '\033[31m%s\033[0m\n' "$1" >&2; exit 1; }

# Random string from an unambiguous alphabet (cryptographic source).
secret() { LC_ALL=C tr -dc 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789' </dev/urandom | head -c "$1"; }
# Meets SQL Server's and the app's password policy; only letters, digits and '-' (safe in .env, compose, sqlcmd).
password() { printf '%s-Aa9' "$(secret 24)"; }
env_value() { grep -E "^$1=" .env | head -n1 | cut -d= -f2- | tr -d '\r'; }

# ---- 1. Docker ----
step 'Checking Docker'
docker info >/dev/null 2>&1 || fail 'Docker is not running. Start Docker, then run this script again.'

# ---- 2. .env ----
created_env=false
admin_password=''
if [[ -f .env ]]; then
  step '.env exists - using it as is'
else
  step 'Creating .env with generated secrets'
  admin_password="$(password)"
  umask 077
  cat > .env <<EOF
# Generated by scripts/start.sh on $(date '+%Y-%m-%d %H:%M'). Local development only.
# Contains secrets: never commit this file (it is git-ignored).
COMPOSE_PROJECT_NAME=smarttask

API_HTTP_PORT=5180
API_HTTPS_PORT=7180
WEB_PORT=4200
SQL_PORT=1433

SQLSERVER_DATA_DIR=$HOME/.smarttask/sqlserver-data

MSSQL_SA_PASSWORD=$(password)
APP_DB_NAME=SmartTaskDb
APP_DB_USER=smarttask_app
APP_DB_PASSWORD=$(password)

JWT_SIGNING_KEY=$(secret 64)

CERT_PASSWORD=$(secret 32)
CERT_DIR=$HOME/.aspnet/https

# Optional: GitHub Models key; empty = the built-in fake AI provider
AI_API_KEY=

# First admin, created on the first start (only when no admin exists yet)
BOOTSTRAP_ADMIN_FIRST_NAME=System
BOOTSTRAP_ADMIN_LAST_NAME=Admin
BOOTSTRAP_ADMIN_EMAIL=admin@smarttask.local
BOOTSTRAP_ADMIN_PASSWORD=$admin_password
EOF
  umask 022
  created_env=true
fi

for key in SQLSERVER_DATA_DIR MSSQL_SA_PASSWORD APP_DB_USER APP_DB_PASSWORD JWT_SIGNING_KEY CERT_PASSWORD CERT_DIR; do
  value="$(env_value "$key")"
  [[ -n "$value" && "$value" != \<* ]] || fail ".env has no value for $key. Fill it in, or delete .env to have one generated."
done
data_dir="$(env_value SQLSERVER_DATA_DIR)"
cert_dir="$(env_value CERT_DIR)"
cert_password="$(env_value CERT_PASSWORD)"
web_port="$(env_value WEB_PORT)"; web_port="${web_port:-4200}"
api_port="$(env_value API_HTTPS_PORT)"; api_port="${api_port:-7180}"

# ---- 3. Data folders ----
step "SQL Server data folders in $data_dir"
mkdir -p "$data_dir/data" "$data_dir/log"

# ---- 4. HTTPS certificate for the API container ----
pfx="$cert_dir/smarttask-api.pfx"
if [[ -f "$pfx" ]]; then
  step 'HTTPS certificate exists'
else
  step "Creating HTTPS certificate $pfx"
  mkdir -p "$cert_dir"
  if command -v dotnet >/dev/null 2>&1; then
    dotnet dev-certs https -ep "$pfx" -p "$cert_password" >/dev/null || fail 'dotnet dev-certs could not export the certificate.'
  else
    # No .NET SDK: make a self-signed localhost certificate with OpenSSL in a throwaway container.
    docker run --rm -e "PFX_PASSWORD=$cert_password" -v "$cert_dir:/out" alpine:3.22 sh -c \
      'apk add --no-cache openssl >/dev/null && openssl req -x509 -newkey rsa:2048 -nodes -days 365 -subj "/CN=localhost" -addext "subjectAltName=DNS:localhost" -keyout /tmp/k.pem -out /tmp/c.pem 2>/dev/null && openssl pkcs12 -export -out /out/smarttask-api.pfx -inkey /tmp/k.pem -in /tmp/c.pem -passout env:PFX_PASSWORD' \
      || fail 'Could not create the certificate with OpenSSL.'
  fi
fi

# ---- 5. Start ----
step 'Starting containers (first build takes a few minutes)'
if [[ "${1:-}" == '--no-build' ]]; then build=(); else build=(--build); fi
docker compose up -d "${build[@]}" \
  || fail 'docker compose failed. If a port is in use, change WEB_PORT / API_HTTPS_PORT / SQL_PORT in .env and run again.'

# ---- 6. Wait until it answers ----
step 'Waiting for the API and the web app'
ready=false
for _ in $(seq 1 60); do
  sleep 3
  api="$(curl -sk -o /dev/null -w '%{http_code}' "https://localhost:$api_port/health/ready" || true)"
  web="$(curl -s -o /dev/null -w '%{http_code}' "http://localhost:$web_port/healthz" || true)"
  if [[ "$api" == 200 && "$web" == 200 ]]; then ready=true; break; fi
done
$ready || fail 'Not ready after 3 minutes. Check: docker compose ps   and   docker compose logs api'

# ---- 7. Summary ----
printf '\n\033[32mSmart Task is running\033[0m\n'
echo "  Web app : http://localhost:$web_port"
echo "  Swagger : https://localhost:$api_port/swagger"
echo "  Admin   : $(env_value BOOTSTRAP_ADMIN_EMAIL)"
if $created_env; then
  printf '  Password: \033[33m%s\033[0m\n' "$admin_password"
  echo '            (generated now; it is also in .env as BOOTSTRAP_ADMIN_PASSWORD)'
else
  echo '  Password: BOOTSTRAP_ADMIN_PASSWORD in .env (if this admin was created from .env)'
fi
echo '  Stop    : docker compose stop'
